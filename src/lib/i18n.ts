const DICTS: Record<Language, Dict> = { en, "pt-BR": ptBR, es };

type I18nState = {
  lang: Language;
  setLang: (l: Language) => void;
};

export const useI18n = create<I18nState>((set) => ({
  lang: "en",
  setLang: (lang) => set({ lang }),
}));

/** Non-reactive translate (for use outside React render). */
export const translate = (key: string): string => {
  const lang = useI18n.getState().lang;
  return DICTS[lang][key] ?? DICTS.en[key] ?? key;
};

/**
 * Hook returning a `t` bound to the CURRENT language. Subscribes to `lang` so
 * components re-render (and re-translate) when the language changes.
 */
export const useT = () => {
  const lang = useI18n((s) => s.lang);
  return (key: string) => DICTS[lang][key] ?? DICTS.en[key] ?? key;
};
